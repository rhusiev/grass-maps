import java.nio.file.Paths
import java.security.MessageDigest

/** One file of a test region package, as its `manifest.json` describes it. */
data class TestRegionComponent(
    val kind: String,
    val file: String,
    val format: String,
    val formatVersion: Int,
    val version: String,
    val zoomLevels: List<Int>,
    val bytes: Long,
    val sha256: String,
    val standIn: Boolean,
)

/**
 * The region package manifest of `data-formats.md` section 2, in the shape the
 * test fixture writes: OSM timestamp, format versions, size and sha256 per
 * file. This reader exists only for tests; `regions` owns the production one.
 */
data class TestRegionManifest(
    val region: String,
    val version: String,
    val packageFormat: Int,
    val osmTimestamp: String,
    val components: List<TestRegionComponent>,
) {
    fun component(kind: String): TestRegionComponent? = components.firstOrNull { it.kind == kind }
}

/**
 * A test region package on disk: `<root>/manifest.json` plus its components.
 */
class TestRegion(
    val root: Path,
    val manifest: TestRegionManifest,
) {
    fun file(component: TestRegionComponent): Path = root.resolve(component.file)

    /**
     * Every mismatch between the manifest and the files, empty when the package
     * is intact. A missing file, a wrong size or a wrong sha256 is an error, so
     * a test that passes proves the committed bytes are the ones recorded.
     */
    fun problems(): List<String> =
        buildList {
            if (manifest.packageFormat != PACKAGE_FORMAT) {
                add("packageFormat ${manifest.packageFormat} is not $PACKAGE_FORMAT")
            }
            if (manifest.osmTimestamp.isBlank()) {
                add("osmTimestamp is empty")
            }
            val duplicateKinds = manifest.components.groupBy { it.kind }.filterValues { it.size > 1 }
            for (kind in duplicateKinds.keys) {
                add("duplicate component kind '$kind'")
            }
            for (component in manifest.components) {
                addAll(componentProblems(component))
            }
        }

    private fun componentProblems(component: TestRegionComponent): List<String> {
        val problems = mutableListOf<String>()
        val file = file(component)
        if (!Files.isRegularFile(file)) {
            return listOf("missing component file: $file")
        }
        val size = Files.size(file)
        if (size != component.bytes) {
            problems += "${component.file}: manifest says ${component.bytes} bytes, file has $size"
        }
        val digest = sha256(file)
        if (digest != component.sha256) {
            problems += "${component.file}: sha256 $digest does not match the manifest"
        }
        if (component.formatVersion < 1) {
            problems += "${component.file}: formatVersion must be at least 1"
        }
        if (component.bytes <= 0) {
            problems += "${component.file}: bytes must be positive"
        }
        if (component.zoomLevels.isNotEmpty() &&
            (component.zoomLevels.size != 2 || component.zoomLevels[0] > component.zoomLevels[1])
        ) {
            problems += "${component.file}: zoomLevels must be [min, max]"
        }
        return problems
    }

    companion object {
        const val PACKAGE_FORMAT = 1
    }
}

/**
 * Loads the committed test region. The package is generated by
 * `tools/pipeline/build-test-region.sh`, not by the test.
 */
object TestRegions {
    const val DEFAULT_REGION = "fixture-mini"
    const val DEFAULT_VERSION = "2026-11-03-1"

    fun load(
        region: String = DEFAULT_REGION,
        version: String = DEFAULT_VERSION,
    ): TestRegion {
        val root = repositoryRoot().resolve("test-data/regions/$region/$version")
        val manifestFile = root.resolve("manifest.json")
        check(Files.isRegularFile(manifestFile)) {
            "Test region not found at $manifestFile. Run tools/pipeline/build-test-region.sh"
        }
        val manifest = readManifest(manifestFile)
        check(manifest.region == region) {
            "manifest region '${manifest.region}' does not match requested '$region'"
        }
        check(manifest.version == version) {
            "manifest version '${manifest.version}' does not match requested '$version'"
        }
        return TestRegion(root, manifest)
    }

    /**
     * The repository root, found by walking up from the test working directory.
     * `grassmaps.repoRoot` overrides it when a test runs outside Gradle.
     */
    fun repositoryRoot(): Path {
        System.getProperty(OVERRIDE_PROPERTY)?.let { return Paths.get(it).toAbsolutePath() }
        var directory: Path? = Paths.get(System.getProperty("user.dir")).toAbsolutePath()
        while (directory != null) {
            if (Files.isRegularFile(directory.resolve("settings.gradle.kts")) &&
                Files.isDirectory(directory.resolve("test-data"))
            ) {
                return directory
            }
            directory = directory.parent
        }
        error("Cannot find the repository root from ${System.getProperty("user.dir")}")
    }

    private fun readManifest(file: Path): TestRegionManifest {
        val root = Json.parseToJsonElement(String(Files.readAllBytes(file), StandardCharsets.UTF_8)).jsonObject
        return TestRegionManifest(
            region = root.string("region", file),
            version = root.string("version", file),
            packageFormat = root.int("packageFormat", file),
            osmTimestamp = root.string("osmTimestamp", file),
            components =
                root.getValue("components").jsonArray.map { element ->
                    component(element.jsonObject, file)
                },
        )
    }

    private fun component(
        json: JsonObject,
        file: Path,
    ): TestRegionComponent =
        TestRegionComponent(
            kind = json.string("kind", file),
            file = json.string("file", file),
            format = json.string("format", file),
            formatVersion = json.int("formatVersion", file),
            version = json.string("version", file),
            zoomLevels = json["zoomLevels"]?.jsonArray?.map { it.jsonPrimitive.int } ?: emptyList(),
            bytes = json.getValue("bytes").jsonPrimitive.long,
            sha256 = json.string("sha256", file),
            standIn = json.getValue("standIn").jsonPrimitive.boolean,
        )

    private fun JsonObject.string(
        key: String,
        file: Path,
    ): String {
        val value = getValue(key).jsonPrimitive
        check(value.isString) { "$file: '$key' must be a string" }
        check(value.content.isNotBlank()) { "$file: '$key' is empty" }
        return value.content
    }

    private fun JsonObject.int(
        key: String,
        file: Path,
    ): Int = getValue(key).jsonPrimitive.int.also { check(it >= 1) { "$file: '$key' must be positive" } }

    private const val OVERRIDE_PROPERTY = "grassmaps.repoRoot"
}

private const val SHA256_BUFFER_BYTES = 64 * 1024

private fun sha256(file: Path): String {
    val digest = MessageDigest.getInstance("SHA-256")
    Files.newInputStream(file).use { input ->
        val buffer = ByteArray(SHA256_BUFFER_BYTES)
        while (true) {
            val read = input.read(buffer)
            if (read < 0) {
                break
            }
            digest.update(buffer, 0, read)
        }
    }
    return digest.digest().joinToString("") { "%02x".format(it.toInt() and 0xff) }
}
